"""Generates src/AgentMemory.Packs.Format/NfcTables.cs: the Unicode data for NFC (UAX #15) from Python's unicodedata.

usage: python -I eng/gen-nfc-tables.py src/AgentMemory.Packs.Format/NfcTables.cs

The pack format's JSON profile requires every string in NFC. .NET under invariant globalization reads every string as
normalized, so the format library normalizes by itself there, from these tables:
- full canonical decompositions (Hangul syllables are algorithmic and left out);
- canonical combining classes above 0;
- primary composites: the pairs NFC composes back (composition exclusions left out).
"""
import sys
import unicodedata

out = sys.argv[1]
decompositions, ccc, pairs = [], {}, []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
        continue
    c = chr(cp)
    nfd = unicodedata.normalize("NFD", c)
    if nfd != c:
        decompositions.append((cp, [ord(x) for x in nfd]))
    k = unicodedata.combining(c)
    if k:
        ccc[cp] = k
    d = unicodedata.decomposition(c)
    if d and not d.startswith("<"):
        parts = [int(x, 16) for x in d.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == c:
            pairs.append((parts[0], parts[1], cp))


def ints(values, per_line=12):
    lines, line = [], []
    for v in values:
        line.append(f"0x{v:X}")
        if len(line) == per_line:
            lines.append("        " + ", ".join(line) + ",")
            line = []
    if line:
        lines.append("        " + ", ".join(line) + ",")
    return "\n".join(lines)


ccc_ranges = []
for cp, k in sorted(ccc.items()):
    if ccc_ranges and ccc_ranges[-1][1] == cp - 1 and ccc_ranges[-1][2] == k:
        ccc_ranges[-1] = (ccc_ranges[-1][0], cp, k)
    else:
        ccc_ranges.append((cp, cp, k))
flat = []
for cp, parts in decompositions:
    flat += [cp, len(parts), *parts]

code = f"""// <auto-generated>
// Generated by eng/gen-nfc-tables.py from Python's unicodedata (Unicode {unicodedata.unidata_version}). Do not edit by hand.
// </auto-generated>
namespace AgentMemory.Packs.Format;

/// <summary>The Unicode data for NFC (UAX #15, Unicode {unicodedata.unidata_version}), for hosts that cannot normalize.</summary>
internal static class NfcTables
{{
    /// <summary>Unicode version the tables were generated from.</summary>
    internal const string UnicodeVersion = "{unicodedata.unidata_version}";

    /// <summary>Full canonical decompositions, Hangul syllables left out: code point, length, then that many code points.</summary>
    internal static readonly int[] Decompositions =
    [
{ints(flat)}
    ];

    /// <summary>Primary composites as first, second, composite triples: what NFC composes (Hangul is algorithmic).</summary>
    internal static readonly int[] Compositions =
    [
{ints([v for p in pairs for v in p])}
    ];

    /// <summary>Canonical combining classes above 0, as start, end, class triples.</summary>
    internal static readonly int[] CombiningClasses =
    [
{ints([v for r in ccc_ranges for v in r])}
    ];
}}
"""
open(out, "w", encoding="utf-8", newline="\n").write(code)
print(f"decompositions: {len(decompositions)}; compositions: {len(pairs)}; combining classes: {len(ccc)} in {len(ccc_ranges)} ranges")
